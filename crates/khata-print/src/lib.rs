/// Which of the invoice prints a document uses.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum InvoiceLayout {
    /// [`invoice_html`].
    #[default]
    English,
    /// [`invoice_html_bilingual`]: every label in English and Arabic (KSA, UAE).
    Bilingual,
    /// [`invoice_html_ar`]: Arabic, right to left.
    Arabic,
}

/// A print in a company's design: the [`InvoiceLayout`] with `look` (template,
/// colour, font, paper, logo, bank details, terms, toggles). The KSA QR
/// and the Hijri date come from `inv.seller_qr` and `inv.hijri`. Whatever
/// the design, the print keeps every field the plain print has, except the
/// columns and lines the design hides and `look.required` does not keep.
pub fn invoice_html_styled(h: &Header, inv: &InvoiceDoc, layout: InvoiceLayout, look: &Look) -> String {
    match layout {
        InvoiceLayout::English => invoice_html_en(h, inv, look),
        InvoiceLayout::Arabic => invoice_ar(h, inv, inv.hijri.as_deref(), look),
        InvoiceLayout::Bilingual => {
            let html = invoice_bilingual(h, inv, &ArabicLabels::default(), inv.seller_qr.as_ref(), look);
            with_hijri(html, inv, inv.hijri.as_deref())
        }
    }
}

/// The parts of an invoice that designs add, in one layout's labels.
struct Extras<'a> {
    inv: &'a InvoiceDoc,
    look: &'a Look<'a>,
    layout: InvoiceLayout,
}

impl Extras<'_> {
    /// A label: English, "English / Arabic" or Arabic.
    fn label(&self, en: &str) -> String {
        match (self.layout, labels::arabic(en)) {
            (InvoiceLayout::Bilingual, Some(ar)) => bi_inline(en, ar),
            (InvoiceLayout::Arabic, Some(ar)) => ar.to_owned(),
            _ => esc(en),
        }
    }

    /// User text in its own direction.
    fn text(&self, s: &str) -> String {
        match self.layout {
            InvoiceLayout::English => esc(s),
            InvoiceLayout::Bilingual => auto(s),
            InvoiceLayout::Arabic => bdi(s),
        }
    }

    /// Several lines of user text.
    fn lines(&self, s: &str) -> String {
        s.lines().filter(|l| !l.trim().is_empty()).map(|l| self.text(l.trim())).collect::<Vec<_>>().join("<br>")
    }

    fn address(&self, a: &str) -> String {
        if a.trim().is_empty() { String::new() } else { format!("<div class=\"addr-lines\">{}</div>", self.lines(a)) }
    }

    /// The ship-to box, between the buyer's and the number's.
    fn ship_box(&self) -> String {
        let Some(s) = self.inv.ship_to.as_ref().filter(|s| !(s.name.trim().is_empty() && s.address.trim().is_empty())) else {
            return String::new();
        };
        format!(
            "<div class=\"box inv-ship\"><div class=\"label\">{}</div><div class=\"strong\">{}</div>{}</div>",
            self.label("Ship to"),
            self.text(&s.name),
            self.address(&s.address)
        )
    }

    fn kv(&self, en: &str, value: &str) -> String {
        if value.trim().is_empty() {
            return String::new();
        }
        format!("<div class=\"kv\"><span class=\"label\">{}</span> <span>{}</span></div>", self.label(en), self.text(value))
    }

    /// Export shipping details, under the party boxes.
    fn export(&self) -> String {
        let Some(e) = self.inv.export.as_ref().filter(|e| !e.is_empty()) else { return String::new() };
        let sb_date = e.shipping_bill_date.map(date).unwrap_or_default();
        let rows = [
            self.kv("Port of loading", &e.port_of_loading),
            self.kv("Port of discharge", &e.port_of_discharge),
            self.kv("Incoterms", &e.incoterms),
            self.kv("Country of destination", &e.destination_country),
            self.kv("Shipping bill no.", &e.shipping_bill_no),
            self.kv("Shipping bill date", &sb_date),
        ]
        .concat();
        format!("<div class=\"inv-export\"><div class=\"inv-h\">{}</div><div class=\"kvs\">{rows}</div></div>", self.label("Export details"))
    }

    /// The foreign-currency lines, under the totals: the rate, then the
    /// base-currency figures the country asks for.
    fn currency(&self, grouping: Grouping) -> String {
        let Some(c) = &self.inv.currency else { return String::new() };
        let both = |en: &str, ar: &str| match self.layout {
            InvoiceLayout::English => esc(en),
            InvoiceLayout::Bilingual => bi_inline(en, ar),
            InvoiceLayout::Arabic => format!("<bdi>{}</bdi>", esc(ar)),
        };
        let (en, ar) = c.headline();
        let mut out = format!("<div class=\"inv-currency\"><div>{}</div>", both(&en, &ar));
        for (en, ar, a) in c.base_figures() {
            out.push_str(&format!("<div class=\"kv\"><span class=\"label\">{}:</span> <strong>{}</strong></div>", both(&en, &ar), format_amount(a, grouping, 2)));
        }
        out.push_str("</div>");
        out
    }

    /// Statutory notes, bank details, terms and the declaration.
    fn closing(&self) -> String {
        let mut out = String::new();
        if !self.inv.legal_notes.is_empty() {
            out.push_str("<div class=\"inv-legal\">");
            for n in &self.inv.legal_notes {
                out.push_str(&format!("<div class=\"legal\">{}</div>", esc(&n.text)));
                if self.layout != InvoiceLayout::English
                    && let Some(ar) = &n.arabic
                {
                    out.push_str(&format!("<div class=\"legal\" lang=\"ar\" dir=\"rtl\">{}</div>", esc(ar)));
                }
            }
            out.push_str("</div>");
        }
        if !self.look.trade_document {
            return out;
        }
        let d = self.look.design;
        let mut info = String::new();
        if !d.bank.is_empty() {
            let b = &d.bank;
            let l = self.look.bank_labels;
            let mut rows = [
                self.kv("Account name", &b.account_name),
                self.kv("Bank", &b.bank_name),
                self.kv("Branch", &b.branch),
                self.kv(l.account_number, &b.account_number),
                self.kv("IBAN", &b.iban),
            ]
            .concat();
            if let Some(code) = l.local_code {
                rows.push_str(&self.kv(code, &b.local_code));
            }
            rows.push_str(&self.kv("SWIFT / BIC", &b.swift));
            info.push_str(&format!("<div class=\"inv-bank\"><div class=\"inv-h\">{}</div>{rows}</div>", self.label("Bank details")));
        }
        if !d.terms.trim().is_empty() {
            info.push_str(&format!("<div class=\"inv-terms\"><div class=\"inv-h\">{}</div><div>{}</div></div>", self.label("Terms and conditions"), self.lines(&d.terms)));
        }
        if !info.is_empty() {
            out.push_str(&format!("<div class=\"inv-info\">{info}</div>"));
        }
        if !d.declaration.trim().is_empty() {
            out.push_str(&format!("<div class=\"inv-decl\"><div class=\"inv-h\">{}</div><div>{}</div></div>", self.label("Declaration"), self.lines(&d.declaration)));
        }
        out
    }

    /// The space for the signature: the image when there is one.
    fn signature(&self) -> String {
        match self.look.signature {
            Some(img) => format!("<br><img class=\"sig\" src=\"{}\" alt=\"\"><br>", img.data_url()),
            None => "<br><br><br>".into(),
        }
    }

    fn footer(&self) -> String {
        let f = &self.look.design.footer;
        if f.trim().is_empty() { String::new() } else { format!("<div class=\"inv-footer\">{}</div>", self.lines(f)) }
    }

    /// The logo in the header, and the design's CSS.
    fn style(&self, mut html: String) -> String {
        if let Some(logo) = self.look.logo
            && let Some(i) = html.find("<header>")
        {
            html.insert_str(i + "<header>".len(), &format!("<div class=\"inv-logo\"><img src=\"{}\" alt=\"\"></div>", logo.data_url()));
        }
        let paper = self.look.paper;
        let margin = match paper {
            Paper::Thermal80 => "3mm",
            Paper::A5 => "9mm 8mm",
            _ => "14mm 12mm",
        };
        html = html.replacen("@page { size: A4; margin: 14mm 12mm; }", &format!("@page {{ size: {}; margin: {margin}; }}", paper.css()), 1);
        html.replacen("</style>", &format!("{}</style>", theme_css(self.look, self.layout)), 1)
    }
}

