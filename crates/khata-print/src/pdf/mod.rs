//! Direct PDF export of invoices, credit and debit notes and vouchers.
//!
//! Pure Rust, so it works the same on Windows, macOS, Linux, Android and
//! iOS (the webviews' print-to-PDF differs on each, and phones have no
//! print dialog). The PDF is written by hand like the Factur-X writer in
//! khata-en16931, but with a real layout: fonts for every script (DejaVu
//! Sans and ten Noto fonts bundled, system fonts for CJK; subset per file;
//! `font.rs`), OpenType shaping with rustybuzz and the Unicode
//! Bidirectional Algorithm (`shape.rs`), PNG and JPEG images (`image.rs`),
//! wrapped text, tables split across pages with their header repeated, a
//! mirrored right-to-left page for Arabic (`layout.rs`), and the writer
//! (`writer.rs`).
//!
//! The layout fills a display list; [`invoices_pdf`] serialises it and
//! [`invoices_pdf_text`] returns the text of every run drawn from the same
//! pass, so tests check what the PDF shows.
//!
//! Each document prints, whatever its template: the logo; the company's
//! name, address and tax number; the title (English and Arabic on bilingual
//! documents) with the KSA QR code; a CANCELLED mark; tax-authority blocks
//! (IRN, CFDI stamp) with their QR; the buyer (name, address, tax number),
//! the ship-to address, number, date (and Hijri date) and place of supply;
//! the currency section; export details; the lines (HSN/SAC or tax class and
//! quantity/rate columns as the design and the law say); taxable value,
//! taxes, other ledgers and total; amount in words; narration; every legal
//! note; bank details, terms and declaration (trade documents); the
//! signatory; the footer note; and "Generated by KhataOS · Page x of y".
//!
//! Limits: a character no bundled, added or system font has prints as "?"
//! (and copies as itself). The font choice of the design applies to
//! printing; the PDF always uses its own fonts.

