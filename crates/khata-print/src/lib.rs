fn invoice_html_en(h: &Header, inv: &InvoiceDoc, look: &Look) -> String {
    let x = Extras { inv, look, layout: InvoiceLayout::English };
    let f = |a: Amount| format_amount(a, h.grouping, 2);
    let mut d = Doc::new(h, &inv.title, "");
    if let Some((label, id)) = &inv.seller_tax {
        let region = inv.seller_region.as_deref().map(|r| format!(" · {r}")).unwrap_or_default();
        d.body.push_str(&format!("<div style=\"text-align:center;font-size:9.5pt\">{}: {}{}</div>", esc(label), esc(id), esc(&region)));
    }
    if inv.cancelled {
        d.body.push_str("<div class=\"void\">CANCELLED</div>");
    }
    let mut buyer = format!("<div class=\"label\">Bill to</div><div class=\"strong\">{}</div>", esc(&inv.buyer_name));
    buyer.push_str(&x.address(&inv.buyer_address));
    if let Some((label, id)) = &inv.buyer_tax {
        buyer.push_str(&format!("<div>{}: {}</div>", esc(label), esc(id)));
    }
    let mut meta = format!(
        "<div class=\"label\">Number</div><div class=\"strong\">{}</div><div class=\"label\">Date</div><div>{}</div>",
        esc(&inv.number),
        date(inv.date)
    );
    if let Some(p) = &inv.place_of_supply {
        meta.push_str(&format!("<div class=\"label\">Place of supply</div><div>{}</div>", esc(p)));
    }
    d.body.push_str(&format!("<div class=\"inv-meta\"><div class=\"box\">{buyer}</div>{}<div class=\"box\">{meta}</div></div>", x.ship_box()));
    d.body.push_str(&x.export());

    let has_class = look.show_tax_class() && inv.lines.iter().any(|l| l.tax_class.is_some());
    let has_qty = look.show_qty_rate() && inv.lines.iter().any(|l| l.qty.is_some());
    let mut heads: Vec<(&str, bool)> = vec![("#", true), ("Description", false)];
    if has_class {
        heads.push((class_heading(inv), false));
    }
    if has_qty {
        heads.extend([("Quantity", true), ("Rate", true)]);
    }
    heads.push(("Amount", true));
    let rows: Vec<Vec<String>> = inv
        .lines
        .iter()
        .enumerate()
        .map(|(i, l)| {
            let mut r = vec![(i + 1).to_string(), l.description.clone()];
            if has_class {
                r.push(l.tax_class.clone().unwrap_or_default());
            }
            if has_qty {
                r.push(l.qty.clone().unwrap_or_default());
                r.push(l.rate.map(f).unwrap_or_default());
            }
            r.push(f(l.amount));
            r
        })
        .collect();
    let blank = heads.len() - 3; // the cells between the label and the amount
    let row = |label: &str, a: Amount| {
        let mut r = vec![String::new(), label.to_owned()];
        r.extend(std::iter::repeat_n(String::new(), blank));
        r.push(f(a));
        r
    };
    let mut all = rows;
    let taxable: Amount = inv.lines.iter().map(|l| l.amount).sum();
    if !inv.taxes.is_empty() || !inv.others.is_empty() {
        all.push(row("Taxable value", taxable));
    }
    for (label, a) in inv.taxes.iter().chain(&inv.others) {
        all.push(row(label, *a));
    }
    d.table(&heads, &all, Some(row("Total", inv.total)));
    d.body.push_str(&x.currency(h.grouping));
    if look.design.show_amount_in_words {
        d.body.push_str(&format!("<div class=\"words\">Amount in words: <strong>{}</strong></div>", esc(&inv.total_in_words)));
    }
    if !inv.narration.trim().is_empty() {
        d.body.push_str(&format!("<div class=\"words\">{}</div>", esc(&inv.narration)));
    }
    d.body.push_str(&x.closing());
    if look.show_signatory() {
        d.body.push_str(&format!("<div class=\"sign\">For {}{}Authorised signatory</div>", esc(h.company), x.signature()));
    }
    d.body.push_str(&x.footer());
    let html = d.finish(&format!("{} {}", inv.title, inv.number)).replacen("</style>", &format!("{INVOICE_CSS}</style>"), 1);
    x.style(html)
}

