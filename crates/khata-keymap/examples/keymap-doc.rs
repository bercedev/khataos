/// The generated block, markers included.
pub fn render() -> String {
    let km = Keymap::tally_prime();
    let mut out = String::new();
    out.push_str(START);
    out.push('\n');
    for &(context, title, intro) in SECTIONS {
        out.push_str(&format!(
            "\n### {title}\n\n{intro}\n\n| Key | What it does | Works today? |\n|---|---|---|\n"
        ));
        for b in km.bindings().iter().filter(|b| b.context == context) {
            let (what, status) = describe(context, b.action);
            out.push_str(&format!(
                "| `{}` | {} | {} |\n",
                b.chord,
                what,
                status.cell()
            ));
        }
    }
    out.push('\n');
    out.push_str(END);
    out
}

/// `page` with its generated block replaced by `render()`, or None if the markers are missing.
pub fn splice(page: &str) -> Option<String> {
    let start = page.find(START)?;
    let end = page[start..].find(END)? + start + END.len();
    Some(format!("{}{}{}", &page[..start], render(), &page[end..]))
}

fn main() {
    if std::env::args().any(|a| a == "--write") {
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(GUIDE);
        let page = std::fs::read_to_string(&path)
            .unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
        let new = splice(&page)
            .unwrap_or_else(|| panic!("{} has no {START} … {END} markers", path.display()));
        if new != page {
            std::fs::write(&path, new).unwrap_or_else(|e| panic!("write {}: {e}", path.display()));
            eprintln!("updated {}", path.display());
        } else {
            eprintln!("{} is up to date", path.display());
        }
    } else {
        println!("{}", render());
    }
}
