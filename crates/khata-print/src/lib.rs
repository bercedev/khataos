// ------------------------------------------------- Schedule III (India)

/// What a row of a Schedule III statement is.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Schedule3RowKind {
    /// A caption without figures ("EQUITY AND LIABILITIES", "Current assets").
    Heading,
    /// A line item, with its note number.
    Line,
    /// A total or a result ("Total", "Profit before tax").
    Total,
}

/// One row of a Schedule III statement in the vertical format. The
/// statement itself is built by `khata_in::schedule3`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Schedule3Row {
    pub kind: Schedule3RowKind,
    /// Indent level, 0 for the main headings.
    pub level: u8,
    pub label: String,
    pub note: Option<u32>,
    pub current: Amount,
    pub previous: Amount,
}

const SCHEDULE3_CSS: &str = "
.s3-unit { text-align: right; font-size: 9pt; margin: 4px 0; }
.s3 td.note { text-align: center; width: 5em; }
.s3 th.note { text-align: center; }
.s3 tr.head td { font-weight: 700; border-bottom: none; padding-top: 6px; }
.s3 tr.total td { border-top: 1pt solid #111; border-bottom: 1pt solid #111; font-weight: 700; }
.s3 td.l1 { padding-left: 14px; } .s3 td.l2 { padding-left: 28px; } .s3 td.l3 { padding-left: 42px; }
";

fn schedule3_html(h: &Header, title: &str, period: &str, heads: (&str, Option<&str>), rows: &[Schedule3Row]) -> String {
    let mut d = Doc::new(h, title, period);
    // Nil figures print as "-", as is usual in Schedule III statements.
    let fig = |a: Amount| if a.is_zero() { "-".to_owned() } else { format_amount(a, h.grouping, 2) };
    d.body.push_str("<div class=\"s3-unit\">(Figures in ₹)</div>");
    d.body.push_str("<table class=\"s3\"><thead><tr><th>Particulars</th><th class=\"note\">Note No.</th>");
    d.body.push_str(&format!("<th class=\"num\">{}</th>", esc(heads.0)));
    if let Some(p) = heads.1 {
        d.body.push_str(&format!("<th class=\"num\">{}</th>", esc(p)));
    }
    d.body.push_str("</tr></thead><tbody>");
    for r in rows {
        let cls = match r.kind {
            Schedule3RowKind::Heading => " class=\"head\"",
            Schedule3RowKind::Line => "",
            Schedule3RowKind::Total => " class=\"total\"",
        };
        let note = r.note.map(|n| n.to_string()).unwrap_or_default();
        d.body.push_str(&format!(
            "<tr{cls}><td class=\"l{}\">{}</td><td class=\"note\">{}</td>",
            r.level.min(3),
            esc(&r.label),
            note
        ));
        let cells: Vec<Amount> = if heads.1.is_some() { vec![r.current, r.previous] } else { vec![r.current] };
        for a in cells {
            let text = if r.kind == Schedule3RowKind::Heading { String::new() } else { fig(a) };
            d.body.push_str(&format!("<td class=\"num\">{text}</td>"));
        }
        d.body.push_str("</tr>");
    }
    d.body.push_str("</tbody></table>");
    d.finish(title).replacen("</style>", &format!("{SCHEDULE3_CSS}</style>"), 1)
}

/// Balance Sheet in the Schedule III (Division I) vertical format, with the
/// previous reporting date's figures alongside when there is one.
pub fn schedule3_balance_sheet_html(
    h: &Header,
    as_at: NaiveDate,
    previous_as_at: Option<NaiveDate>,
    rows: &[Schedule3Row],
) -> String {
    let current = format!("As at {}", date(as_at));
    let previous = previous_as_at.map(|p| format!("As at {}", date(p)));
    schedule3_html(h, "Balance Sheet", &format!("as at {}", date(as_at)), (&current, previous.as_deref()), rows)
}

/// Statement of Profit and Loss in the Schedule III (Division I) vertical
/// format, with the previous period's figures alongside when there is one.
pub fn schedule3_profit_and_loss_html(
    h: &Header,
    period: (NaiveDate, NaiveDate),
    previous: Option<(NaiveDate, NaiveDate)>,
    rows: &[Schedule3Row],
) -> String {
    let label = |(f, t): (NaiveDate, NaiveDate)| format!("{} to {}", date(f), date(t));
    let current = label(period);
    let prev = previous.map(label);
    schedule3_html(
        h,
        "Statement of Profit and Loss",
        &format!("for the period {}", label(period)),
        (&current, prev.as_deref()),
        rows,
    )
}

