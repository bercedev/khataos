struct Doc<'a> {
    h: &'a Header<'a>,
    body: String,
}

impl<'a> Doc<'a> {
    fn new(h: &'a Header<'a>, title: &str, period: &str) -> Self {
        let body = format!(
            "<header><h1>{}</h1><div class=\"addr\">{}</div><h2>{}</h2><div class=\"period\">{}</div></header>",
            esc(h.company),
            esc(h.address),
            esc(title),
            esc(period)
        );
        Self { h, body }
    }

    fn amt(&self, a: Amount) -> String {
        if a.is_zero() { String::new() } else { format_amount(a, self.h.grouping, 2) }
    }

    fn table(&mut self, heads: &[(&str, bool)], rows: &[Vec<String>], total: Option<Vec<String>>) {
        let numeric: Vec<bool> = heads.iter().map(|(_, n)| *n).collect();
        self.body.push_str("<table><thead><tr>");
        for (h, n) in heads {
            self.body.push_str(&format!("<th{}>{}</th>", if *n { " class=\"num\"" } else { "" }, esc(h)));
        }
        self.body.push_str("</tr></thead><tbody>");
        let mut row = |cells: &[String], cls: &str| {
            self.body.push_str(&format!("<tr{cls}>"));
            for (i, c) in cells.iter().enumerate() {
                let num = numeric.get(i).copied().unwrap_or(false);
                self.body.push_str(&format!("<td{}>{}</td>", if num { " class=\"num\"" } else { "" }, esc(c)));
            }
            self.body.push_str("</tr>");
        };
        for r in rows {
            row(r, "");
        }
        if let Some(t) = total {
            row(&t, " class=\"total\"");
        }
        self.body.push_str("</tbody></table>");
    }

    fn finish(self, title: &str) -> String {
        format!(
            "<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\"><title>{} — {}</title><style>{CSS}</style></head><body>{}<footer>Generated by KhataOS</footer></body></html>",
            esc(title),
            esc(self.h.company),
            self.body
        )
    }
}

/// Trial Balance. `opening_stock` (the stock items' opening value) is a
/// debit of its own: it is part of the opening balances but no ledger's.
pub fn trial_balance_html(h: &Header, as_at: NaiveDate, rows: &[TrialBalanceRow], opening_stock: Amount) -> String {
    let mut d = Doc::new(h, "Trial Balance", &format!("As at {}", date(as_at)));
    let mut body: Vec<Vec<String>> = rows.iter().map(|r| vec![r.name.clone(), d.amt(r.debit), d.amt(r.credit)]).collect();
    if !opening_stock.is_zero() {
        body.push(vec!["Opening Stock".into(), d.amt(opening_stock), String::new()]);
    }
    let dr: Amount = rows.iter().map(|r| r.debit).sum::<Amount>() + opening_stock;
    let cr: Amount = rows.iter().map(|r| r.credit).sum();
    let total = vec!["Grand Total".into(), d.amt(dr), d.amt(cr)];
    d.table(&[("Particulars", false), ("Debit", true), ("Credit", true)], &body, Some(total));
    d.finish("Trial Balance")
}

pub fn day_book_html(h: &Header, from: NaiveDate, to: NaiveDate, rows: &[DayBookRow]) -> String {
    let mut d = Doc::new(h, "Day Book", &format!("{} to {}", date(from), date(to)));
    let body: Vec<Vec<String>> = rows
        .iter()
        .map(|r| vec![date(r.date), r.particulars.clone(), format!("{:?}", r.kind), r.number.clone(), d.amt(r.debit), d.amt(r.credit)])
        .collect();
    d.table(
        &[("Date", false), ("Particulars", false), ("Vch Type", false), ("Vch No.", false), ("Debit", true), ("Credit", true)],
        &body,
        None,
    );
    d.finish("Day Book")
}

pub fn ledger_statement_html(h: &Header, ledger: &str, from: NaiveDate, to: NaiveDate, s: &LedgerStatement) -> String {
    let mut d = Doc::new(h, &format!("Ledger: {ledger}"), &format!("{} to {}", date(from), date(to)));
    let bal = |a: Amount| -> String {
        if a.is_zero() {
            "Nil".into()
        } else {
            format!("{} {}", format_amount(a.abs(), h.grouping, 2), if a.is_sign_positive() { "Dr" } else { "Cr" })
        }
    };
    let mut body = vec![vec![date(from), "Opening Balance".into(), String::new(), String::new(), String::new(), String::new(), bal(s.opening)]];
    for r in &s.rows {
        body.push(vec![date(r.date), r.particulars.clone(), format!("{:?}", r.kind), r.number.clone(), d.amt(r.debit), d.amt(r.credit), bal(r.balance)]);
    }
    let total = vec![String::new(), "Closing Balance".into(), String::new(), String::new(), String::new(), String::new(), bal(s.closing)];
    d.table(
        &[("Date", false), ("Particulars", false), ("Vch Type", false), ("Vch No.", false), ("Debit", true), ("Credit", true), ("Balance", true)],
        &body,
        Some(total),
    );
    d.finish("Ledger Statement")
}

pub fn profit_and_loss_html(h: &Header, p: &ProfitAndLoss) -> String {
    let mut d = Doc::new(h, "Profit & Loss A/c", &format!("{} to {}", date(p.from), date(p.to)));
    let side = |rows: &[khata_core::reports::GroupTotal]| -> Vec<Vec<String>> {
        rows.iter().map(|r| vec![r.name.clone(), format_amount(r.amount, h.grouping, 2)]).collect()
    };
    let exp: Amount = p.expenses.iter().map(|r| r.amount).sum();
    let inc: Amount = p.incomes.iter().map(|r| r.amount).sum();
    d.body.push_str("<div class=\"split\"><div>");
    // Stock rows open the trading section, as in a trading account.
    let stock = |label: &str, a: Amount| (!a.is_zero()).then(|| vec![label.to_owned(), format_amount(a, h.grouping, 2)]);
    let mut left: Vec<Vec<String>> = stock("Opening Stock", p.opening_stock).into_iter().collect();
    left.extend(side(&p.expenses));
    if p.net_profit.is_sign_positive() && !p.net_profit.is_zero() {
        left.push(vec!["Net Profit".into(), format_amount(p.net_profit, h.grouping, 2)]);
    }
    let left_total = p.opening_stock + exp + p.net_profit.max(Amount::ZERO);
    d.table(&[("Expenses", false), ("Amount", true)], &left, Some(vec!["Total".into(), format_amount(left_total, h.grouping, 2)]));
    d.body.push_str("</div><div>");
    let mut right = side(&p.incomes);
    right.extend(stock("Closing Stock", p.closing_stock));
    if p.net_profit.is_sign_negative() {
        right.push(vec!["Net Loss".into(), format_amount(-p.net_profit, h.grouping, 2)]);
    }
    let right_total = inc + p.closing_stock + (-p.net_profit).max(Amount::ZERO);
    d.table(&[("Incomes", false), ("Amount", true)], &right, Some(vec!["Total".into(), format_amount(right_total, h.grouping, 2)]));
    d.body.push_str("</div></div>");
    d.finish("Profit & Loss A/c")
}

pub fn balance_sheet_html(h: &Header, b: &BalanceSheet) -> String {
    let mut d = Doc::new(h, "Balance Sheet", &format!("As at {}", date(b.as_at)));
    let f = |a: Amount| format_amount(a, h.grouping, 2);
    let mut liab: Vec<Vec<String>> = b.liabilities.iter().map(|r| vec![r.name.clone(), f(r.amount)]).collect();
    liab.push(vec!["Profit & Loss A/c".into(), f(b.profit_and_loss)]);
    if !b.opening_difference.is_zero() {
        liab.push(vec!["Difference in opening balances".into(), f(b.opening_difference)]);
    }
    let mut assets: Vec<Vec<String>> = b.assets.iter().map(|r| vec![r.name.clone(), f(r.amount)]).collect();
    if !b.closing_stock.is_zero() {
        assets.push(vec!["Closing Stock".into(), f(b.closing_stock)]);
    }
    d.body.push_str("<div class=\"split\"><div>");
    d.table(&[("Liabilities", false), ("Amount", true)], &liab, Some(vec!["Total".into(), f(b.total_liabilities)]));
    d.body.push_str("</div><div>");
    d.table(&[("Assets", false), ("Amount", true)], &assets, Some(vec!["Total".into(), f(b.total_assets)]));
    d.body.push_str("</div></div>");
    d.finish("Balance Sheet")
}

/// One line of an invoice: an item (with quantity and rate) or a service
/// or other ledger line (amount only).
#[derive(Debug, Clone, Default, PartialEq)]
pub struct InvoiceLine {
    pub description: String,
    /// HSN/SAC code or tax category.
    pub tax_class: Option<String>,
    /// Quantity with its unit ("12.5 kg").
    pub qty: Option<String>,
    pub rate: Option<Amount>,
    pub amount: Amount,
}

/// A delivery address different from the buyer's (Rule 46(o) in India).
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct ShipTo {
    pub name: String,
    /// Several lines.
    pub address: String,
}

/// Shipping details of an export invoice. Empty fields are not printed.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct ExportDetails {
    pub port_of_loading: String,
    pub port_of_discharge: String,
    /// The Incoterms rule and place ("FOB Nhava Sheva").
    pub incoterms: String,
    pub destination_country: String,
    /// India: the shipping bill (or bill of export) number and date.
    pub shipping_bill_no: String,
    pub shipping_bill_date: Option<NaiveDate>,
}

impl ExportDetails {
    pub fn is_empty(&self) -> bool {
        [&self.port_of_loading, &self.port_of_discharge, &self.incoterms, &self.destination_country, &self.shipping_bill_no]
            .iter()
            .all(|s| s.trim().is_empty())
            && self.shipping_bill_date.is_none()
    }
}

/// A foreign-currency invoice: every amount of the [`InvoiceDoc`] is in
/// `code`; this prints the rate and the totals in the company's own
/// currency (UAE ER Art 59(1)(k), KSA, Singapore and India ask for the tax
/// or the total in local currency). Filled by the multi-currency code; the
/// renderers only print it.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct CurrencySection {
    /// ISO 4217 code of the invoice currency ("USD").
    pub code: String,
    /// The company's own currency ("INR").
    pub base_code: String,
    /// Units of `base_code` for one unit of `code`.
    pub rate: Amount,
    /// The invoice total in `base_code`.
    pub base_total: Amount,
    /// The tax in `base_code`, when the country asks for it.
    pub base_tax: Option<Amount>,
}

/// One base-currency figure of a foreign-currency invoice: English label,
/// Arabic label, amount.
pub type BaseFigure = (String, String, Amount);

impl CurrencySection {
    /// "Amounts in USD at 1 USD = 83.25 INR" and its Arabic.
    pub fn headline(&self) -> (String, String) {
        let rate = format!("1 {} = {} {}", self.code, self.rate.normalize(), self.base_code);
        (format!("Amounts in {} at {rate}", self.code), format!("المبالغ بعملة {} بسعر {rate}", self.code))
    }

    /// The figures the company's country asks for in its own currency,
    /// told apart by that currency: Singapore the total excluding GST, the
    /// GST and the total including GST in SGD; the UAE, KSA and the UK the
    /// VAT (and total) in AED, SAR or GBP; India the GST (and total) in INR.
    pub fn base_figures(&self) -> Vec<BaseFigure> {
        let b = self.base_code.as_str();
        let tax_name = match b {
            "SGD" | "INR" => "GST",
            "AED" | "SAR" | "GBP" => "VAT",
            _ => "Tax",
        };
        let tax_ar = if tax_name == "VAT" { "ضريبة القيمة المضافة" } else { "الضريبة" };
        let total = (format!("Total in {b}"), format!("الإجمالي بعملة {b}"), self.base_total);
        let Some(tax) = self.base_tax else { return vec![total] };
        let tax_row = (format!("{tax_name} in {b}"), format!("{tax_ar} بعملة {b}"), tax);
        if b == "SGD" {
            return vec![
                (format!("Total excluding GST in {b}"), format!("الإجمالي قبل الضريبة بعملة {b}"), self.base_total - tax),
                tax_row,
                (format!("Total including GST in {b}"), format!("الإجمالي شامل الضريبة بعملة {b}"), self.base_total),
            ];
        }
        vec![tax_row, total]
    }
}

/// A statutory statement every design prints (export endorsement,
/// zero-rating, reverse charge). `arabic` is printed with it on bilingual
/// and Arabic invoices.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct LegalNote {
    pub text: String,
    pub arabic: Option<String>,
}

impl LegalNote {
    pub fn en(text: impl Into<String>) -> Self {
        Self { text: text.into(), arabic: None }
    }
}

/// A box of registration data from a tax authority (India's IRN, Mexico's
/// CFDI stamp), for the PDF writer. HTML prints splice the desktop's own
/// HTML for these blocks instead.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct PrintBlock {
    /// Status lines printed first, in bold ("IRN CANCELLED").
    pub flags: Vec<String>,
    /// (label, value) rows; long values wrap.
    pub rows: Vec<(String, String)>,
    /// A closing line ("Este documento es una representación impresa de un CFDI.").
    pub note: String,
    pub qr: Option<QrSymbol>,
}

/// The heading of the line tax-class column: "HSN/SAC" on an Indian (GSTIN)
/// invoice, "Tax class" (the VAT or GST rate class) everywhere else.
pub(crate) fn class_heading(inv: &InvoiceDoc) -> &'static str {
    let gst_india = [&inv.seller_tax, &inv.buyer_tax].into_iter().flatten().any(|(label, _)| label == "GSTIN");
    if gst_india { "HSN/SAC" } else { "Tax class" }
}

/// A printable invoice, credit note or debit note.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct InvoiceDoc {
    /// "Tax Invoice", "Credit Note"…
    pub title: String,
    pub number: String,
    pub date: NaiveDate,
    /// The company's registration, e.g. ("GSTIN", "27AAPFU0939F1ZV").
    pub seller_tax: Option<(String, String)>,
    /// The company's state or region name.
    pub seller_region: Option<String>,
    pub buyer_name: String,
    /// The buyer's mailing address (several lines; empty when not known).
    pub buyer_address: String,
    pub buyer_tax: Option<(String, String)>,
    pub place_of_supply: Option<String>,
    /// Where the goods go, when not to the buyer's address.
    pub ship_to: Option<ShipTo>,
    pub lines: Vec<InvoiceLine>,
    /// Tax rows ("Output CGST", amount) after the taxable total.
    pub taxes: Vec<(String, Amount)>,
    /// Other ledgers after tax (discount, rounding off…), signed as they add to the total.
    pub others: Vec<(String, Amount)>,
    pub total: Amount,
    pub total_in_words: String,
    /// The total in Arabic words ("فقط … لا غير"), printed under the English
    /// on bilingual KSA/UAE invoices.
    pub total_in_words_ar: Option<String>,
    pub narration: String,
    pub cancelled: bool,
    /// Export shipping details.
    pub export: Option<ExportDetails>,
    /// Foreign-currency details (filled by the multi-currency code).
    pub currency: Option<CurrencySection>,
    /// Statutory statements: printed by every design, never switched off.
    pub legal_notes: Vec<LegalNote>,
    /// KSA: the ZATCA QR code, printed top right.
    pub seller_qr: Option<QrSymbol>,
    /// The date in the Hijri calendar, formatted by the caller.
    pub hijri: Option<String>,
    /// Tax-authority blocks for the PDF (see [`PrintBlock`]).
    pub blocks: Vec<PrintBlock>,
}

