    /// Checks the cross-reference table; returns the page count.
    fn check_structure(pdf: &[u8]) -> usize {
        assert!(pdf.starts_with(b"%PDF-1.7\n%"));
        assert!(pdf.ends_with(b"%%EOF\n"));
        let tail = std::str::from_utf8(&pdf[pdf.len() - 40..]).unwrap_or_default().to_owned();
        let sx: usize = tail.split("startxref\n").nth(1).unwrap().lines().next().unwrap().parse().unwrap();
        assert!(pdf[sx..].starts_with(b"xref\n0 "));
        let table = std::str::from_utf8(&pdf[sx..]).unwrap();
        let count: usize = table.lines().nth(1).unwrap().split(' ').nth(1).unwrap().parse().unwrap();
        for (i, line) in table.lines().skip(3).take(count - 1).enumerate() {
            assert_eq!(line.len(), 19, "20-byte entries ending in space and new line");
            let off: usize = line[..10].parse().unwrap();
            let id = i + 1;
            assert!(pdf[off..].starts_with(format!("{id} 0 obj").as_bytes()), "object {id}");
        }
        let s = String::from_utf8_lossy(pdf);
        s.matches("/Type /Page ").count()
    }

    fn page_sizes(pdf: &[u8]) -> Vec<(f32, f32)> {
        let s = String::from_utf8_lossy(pdf);
        s.match_indices("/MediaBox [0 0 ")
            .map(|(i, m)| {
                let rest = &s[i + m.len()..];
                let mut it = rest.split(']').next().unwrap().split(' ');
                (it.next().unwrap().parse().unwrap(), it.next().unwrap().parse().unwrap())
            })
            .collect()
    }

    fn streams(pdf: &[u8]) -> Vec<Vec<u8>> {
        let mut out = Vec::new();
        let mut at = 0;
        while let Some(i) = find(&pdf[at..], b"stream\n") {
            let start = at + i + 7;
            let end = start + find(&pdf[start..], b"\nendstream").unwrap();
            let mut z = ZlibDecoder::new(&pdf[start..end]);
            let mut buf = Vec::new();
            if z.read_to_end(&mut buf).is_ok() {
                out.push(buf);
            }
            at = end + 10;
        }
        out
    }

