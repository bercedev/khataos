/// A QR symbol to print: `width` × `width` modules, row by row, `true` dark.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct QrSymbol {
    pub width: usize,
    pub dark: Vec<bool>,
}

/// The symbol as an inline SVG, with the 4-module quiet zone QR readers
/// need, one path of horizontal runs.
pub fn qr_svg(q: &QrSymbol, size_mm: u32) -> String {
    let side = q.width + 8;
    let mut path = String::new();
    for y in 0..q.width {
        let mut x = 0;
        while x < q.width {
            if q.dark.get(y * q.width + x).copied().unwrap_or(false) {
                let start = x;
                while x < q.width && q.dark.get(y * q.width + x).copied().unwrap_or(false) {
                    x += 1;
                }
                path.push_str(&format!("M{} {}h{}v1h-{}z", start + 4, y + 4, x - start, x - start));
            } else {
                x += 1;
            }
        }
    }
    format!(
        "<svg xmlns=\"http://www.w3.org/2000/svg\" class=\"qr\" width=\"{size_mm}mm\" height=\"{size_mm}mm\" viewBox=\"0 0 {side} {side}\" shape-rendering=\"crispEdges\" role=\"img\" aria-label=\"QR code\"><rect width=\"{side}\" height=\"{side}\" fill=\"#fff\"/><path fill=\"#000\" d=\"{path}\"/></svg>"
    )
}

