/// "English" with its Arabic below it, marked up as Arabic.
fn bi(en: &str, ar: &str) -> String {
    format!("<span lang=\"en\">{}</span><span class=\"bi-ar\" lang=\"ar\" dir=\"rtl\">{}</span>", esc(en), esc(ar))
}

/// "English / Arabic" on one line.
fn bi_inline(en: &str, ar: &str) -> String {
    format!("<span lang=\"en\">{}</span> / <span lang=\"ar\" dir=\"rtl\">{}</span>", esc(en), esc(ar))
}

/// User text, in whichever direction it is written.
fn auto(s: &str) -> String {
    format!("<span dir=\"auto\">{}</span>", esc(s))
}

/// A tax invoice (or credit/debit note) with every label in English and
/// Arabic, as KSA requires for customer-facing invoices and UAE allows
/// (`docs/research/mena-compliance.md` §5, §8 point 9). Party names, items
/// and narration print as entered, in their own direction. `qr`, when
/// given, prints top right (the ZATCA QR code).
pub fn invoice_html_bilingual(h: &Header, inv: &InvoiceDoc, ar: &ArabicLabels, qr: Option<&QrSymbol>) -> String {
    invoice_bilingual(h, inv, ar, qr, &Look::plain())
}

fn invoice_bilingual(h: &Header, inv: &InvoiceDoc, ar: &ArabicLabels, qr: Option<&QrSymbol>, look: &Look) -> String {
    let x = Extras { inv, look, layout: InvoiceLayout::Bilingual };
    let f = |a: Amount| format_amount(a, h.grouping, 2);
    let title_ar = ar.title(&inv.title).unwrap_or_default();
    let mut body = format!(
        "<div class=\"bi-head\"><header><h1 dir=\"auto\">{}</h1><div class=\"addr\" dir=\"auto\">{}</div><h2>{}</h2></header>{}</div>",
        esc(h.company),
        esc(h.address),
        if title_ar.is_empty() { esc(&inv.title) } else { bi_inline(&inv.title, title_ar) },
        qr.map(|q| qr_svg(q, 30)).unwrap_or_default()
    );
    if let Some((_, id)) = &inv.seller_tax {
        let region = inv.seller_region.as_deref().map(|r| format!(" · {}", auto(r))).unwrap_or_default();
        body.push_str(&format!("<div class=\"bi-seller\">{}: {}{region}</div>", bi_inline("VAT number", &ar.vat_number), esc(id)));
    }
    if inv.cancelled {
        body.push_str(&format!("<div class=\"void\">{}</div>", bi_inline("CANCELLED", &ar.cancelled)));
    }
    let mut buyer = format!("<div class=\"label\">{}</div><div class=\"strong\">{}</div>", bi_inline("Buyer", &ar.buyer), auto(&inv.buyer_name));
    buyer.push_str(&x.address(&inv.buyer_address));
    if let Some((_, id)) = &inv.buyer_tax {
        buyer.push_str(&format!("<div>{}: {}</div>", bi_inline("VAT number", &ar.vat_number), esc(id)));
    }
    let mut meta = format!(
        "<div class=\"label\">{}</div><div class=\"strong\">{}</div><div class=\"label\">{}</div><div>{}</div>",
        bi_inline("Invoice number", &ar.invoice_number),
        esc(&inv.number),
        bi_inline("Date", &ar.date),
        date(inv.date)
    );
    if let Some(p) = &inv.place_of_supply {
        meta.push_str(&format!("<div class=\"label\">{}</div><div>{}</div>", bi_inline("Place of supply", &ar.place_of_supply), auto(p)));
    }
    body.push_str(&format!("<div class=\"inv-meta\"><div class=\"box\">{buyer}</div>{}<div class=\"box\">{meta}</div></div>", x.ship_box()));
    body.push_str(&x.export());

    let has_class = look.show_tax_class() && inv.lines.iter().any(|l| l.tax_class.is_some());
    let has_qty = look.show_qty_rate() && inv.lines.iter().any(|l| l.qty.is_some());
    let mut heads: Vec<(String, bool)> = vec![("#".into(), true), (bi("Description", &ar.description), false)];
    if has_class {
        heads.push((bi("Tax class", &ar.tax_class), false));
    }
    if has_qty {
        heads.push((bi("Quantity", &ar.quantity), true));
        heads.push((bi("Unit price", &ar.unit_price), true));
    }
    heads.push((bi("Amount", &ar.amount), true));
    let num = |n: bool| if n { " class=\"num\"" } else { "" };
    body.push_str("<table><thead><tr>");
    for (cell, n) in &heads {
        body.push_str(&format!("<th{}>{cell}</th>", num(*n)));
    }
    body.push_str("</tr></thead><tbody>");
    for (i, l) in inv.lines.iter().enumerate() {
        body.push_str(&format!("<tr><td class=\"num\">{}</td><td>{}</td>", i + 1, auto(&l.description)));
        if has_class {
            body.push_str(&format!("<td>{}</td>", esc(l.tax_class.as_deref().unwrap_or_default())));
        }
        if has_qty {
            body.push_str(&format!(
                "<td class=\"num\">{}</td><td class=\"num\">{}</td>",
                esc(l.qty.as_deref().unwrap_or_default()),
                l.rate.map(f).unwrap_or_default()
            ));
        }
        body.push_str(&format!("<td class=\"num\">{}</td></tr>", f(l.amount)));
    }
    let blank = heads.len() - 3; // the cells between the label and the amount
    let row = |label: String, a: Amount, cls: &str| {
        format!("<tr{cls}><td></td><td>{label}</td>{}<td class=\"num\">{}</td></tr>", "<td></td>".repeat(blank), f(a))
    };
    let taxable: Amount = inv.lines.iter().map(|l| l.amount).sum();
    if !inv.taxes.is_empty() || !inv.others.is_empty() {
        body.push_str(&row(bi("Total excluding VAT", &ar.taxable_amount), taxable, ""));
    }
    for (label, a) in &inv.taxes {
        let label = if label.to_ascii_lowercase().contains("vat") { bi(label, &ar.vat) } else { auto(label) };
        body.push_str(&row(label, *a, ""));
    }
    for (label, a) in &inv.others {
        body.push_str(&row(auto(label), *a, ""));
    }
    body.push_str(&row(bi("Total including VAT", &ar.total), inv.total, " class=\"total\""));
    body.push_str("</tbody></table>");
    body.push_str(&x.currency(h.grouping));
    if look.design.show_amount_in_words {
        body.push_str(&format!(
            "<div class=\"words\">{}: <strong dir=\"auto\">{}</strong></div>",
            bi_inline("Amount in words", &ar.amount_in_words),
            esc(&inv.total_in_words)
        ));
        if let Some(words) = inv.total_in_words_ar.as_deref().filter(|w| !w.trim().is_empty()) {
            body.push_str(&format!(
                "<div class=\"words\" dir=\"rtl\" lang=\"ar\">{}: <strong>{}</strong></div>",
                esc(&ar.amount_in_words),
                esc(words)
            ));
        }
    }
    if !inv.narration.trim().is_empty() {
        body.push_str(&format!("<div class=\"words\" dir=\"auto\">{}</div>", esc(&inv.narration)));
    }
    body.push_str(&x.closing());
    if look.show_signatory() {
        body.push_str(&format!(
            "<div class=\"sign\">For <span dir=\"auto\">{}</span>{}{}</div>",
            esc(h.company),
            x.signature(),
            bi_inline("Authorised signatory", &ar.signatory)
        ));
    }
    body.push_str(&x.footer());
    let d = Doc { h, body };
    let html = d
        .finish(&format!("{} {}", inv.title, inv.number))
        .replacen("</style>", &format!("{INVOICE_CSS}{BILINGUAL_CSS}</style>"), 1);
    x.style(html)
}

