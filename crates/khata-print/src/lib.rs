// ------------------------------- Schedule III units and notes (India)

/// A Schedule III statement as [`schedule3_balance_sheet_html`] and
/// [`schedule3_profit_and_loss_html`] print it, but with the figures in a
/// rounding unit (`unit` such as "₹ in lakhs"; the rows already rounded).
pub fn schedule3_statement_html(
    h: &Header,
    title: &str,
    period: &str,
    heads: (&str, Option<&str>),
    unit: &str,
    rows: &[Schedule3Row],
) -> String {
    schedule3_html(h, title, period, heads, rows).replacen(
        "<div class=\"s3-unit\">(Figures in ₹)</div>",
        &format!("<div class=\"s3-unit\">(Figures in {})</div>", esc(unit)),
        1,
    )
}

/// A cell of a note table.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Schedule3Cell {
    Empty,
    /// Money in the notes' unit; nil prints as "-".
    Amount(Amount),
    /// Ratios, percentages and words, printed as given.
    Text(String),
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Schedule3NoteRow {
    pub kind: Schedule3RowKind,
    pub level: u8,
    pub label: String,
    pub cells: Vec<Schedule3Cell>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Schedule3NoteTable {
    pub caption: Option<String>,
    pub columns: Vec<String>,
    pub rows: Vec<Schedule3NoteRow>,
}

/// One note to accounts (built by `khata_in::schedule3_notes`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Schedule3Note {
    pub number: u32,
    pub title: String,
    pub tables: Vec<Schedule3NoteTable>,
    /// Disclosures the company must supply, printed under the tables.
    pub remarks: Vec<String>,
}

const SCHEDULE3_NOTES_CSS: &str = "
.s3n { break-inside: auto; margin: 10px 0 14px; }
.s3n h3 { font-size: 10.5pt; margin: 0 0 4px; }
.s3n .cap { font-size: 9pt; font-style: italic; margin: 6px 0 2px; }
.s3n table { margin-bottom: 4px; }
.s3n td.text { white-space: normal; font-size: 8.5pt; }
.s3n ul { margin: 2px 0 0 16px; padding: 0; font-size: 8.5pt; color: #333; }
";

/// Notes to accounts, numbered as on the statements, each with its tables
/// and the disclosures still to be supplied.
pub fn schedule3_notes_html(h: &Header, period: &str, unit: &str, notes: &[Schedule3Note]) -> String {
    let title = "Notes to the financial statements";
    let mut d = Doc::new(h, title, period);
    let fig = |a: Amount| if a.is_zero() { "-".to_owned() } else { format_amount(a, h.grouping, 2) };
    d.body.push_str(&format!("<div class=\"s3-unit\">(Figures in {})</div>", esc(unit)));
    for n in notes {
        d.body.push_str(&format!("<section class=\"s3n\"><h3>{}. {}</h3>", n.number, esc(&n.title)));
        for t in &n.tables {
            if let Some(c) = &t.caption {
                d.body.push_str(&format!("<div class=\"cap\">{}</div>", esc(c)));
            }
            d.body.push_str("<table class=\"s3\"><thead><tr><th>Particulars</th>");
            for c in &t.columns {
                d.body.push_str(&format!("<th class=\"num\">{}</th>", esc(c)));
            }
            d.body.push_str("</tr></thead><tbody>");
            for r in &t.rows {
                let cls = match r.kind {
                    Schedule3RowKind::Heading => " class=\"head\"",
                    Schedule3RowKind::Line => "",
                    Schedule3RowKind::Total => " class=\"total\"",
                };
                d.body.push_str(&format!("<tr{cls}><td class=\"l{}\">{}</td>", r.level.min(3), esc(&r.label)));
                if r.kind != Schedule3RowKind::Heading {
                    for c in &r.cells {
                        match c {
                            Schedule3Cell::Empty => d.body.push_str("<td></td>"),
                            Schedule3Cell::Amount(a) => d.body.push_str(&format!("<td class=\"num\">{}</td>", fig(*a))),
                            Schedule3Cell::Text(s) => d.body.push_str(&format!("<td class=\"text\">{}</td>", esc(s))),
                        }
                    }
                } else {
                    d.body.push_str(&"<td></td>".repeat(t.columns.len()));
                }
                d.body.push_str("</tr>");
            }
            d.body.push_str("</tbody></table>");
        }
        if !n.remarks.is_empty() {
            d.body.push_str("<ul>");
            for r in &n.remarks {
                d.body.push_str(&format!("<li>{}</li>", esc(r)));
            }
            d.body.push_str("</ul>");
        }
        d.body.push_str("</section>");
    }
    d.finish(title).replacen("</style>", &format!("{SCHEDULE3_CSS}{SCHEDULE3_NOTES_CSS}</style>"), 1)
}

