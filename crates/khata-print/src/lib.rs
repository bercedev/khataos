// ---------------------------------------- Arabic prints (right to left)
//
// Arabic variants of the report and voucher prints, chosen by the caller
// (the desktop app passes the display language). The whole document is
// right to left (`dir="rtl" lang="ar"`, also on a wrapper `<main>`, since the
// print window copies only the body's children). Digits stay Latin, as in
// the app (docs/i18n.md); each amount is a left-to-right island so a minus
// stays in front. Names from the books and voucher numbers are `<bdi>`, so
// an English ledger name keeps its own direction. Hijri dates are never
// worked out here: the caller passes the text it already formatted.

/// The language a document prints in.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum PrintLanguage {
    #[default]
    English,
    Arabic,
}

impl PrintLanguage {
    /// From a language code ("ar", "ar-SA", "en"…); anything else is English.
    pub fn from_code(code: Option<&str>) -> Self {
        let c = code.unwrap_or_default().trim().to_ascii_lowercase();
        if c == "ar" || c.starts_with("ar-") { Self::Arabic } else { Self::English }
    }
}

/// Gulf usage, as on screen (`dates.ts`).
const MONTHS_AR: [&str; 12] = ["يناير", "فبراير", "مارس", "أبريل", "مايو", "يونيو", "يوليو", "أغسطس", "سبتمبر", "أكتوبر", "نوفمبر", "ديسمبر"];

/// "19-أكتوبر-2026": the screen's order and Latin digits, Arabic month names.
fn date_ar(d: NaiveDate) -> String {
    use chrono::Datelike;
    format!("{}-{}-{}", d.day(), MONTHS_AR[d.month0() as usize], d.year())
}

/// Text from the books (a name, a number) in its own direction.
fn bdi(s: &str) -> String {
    format!("<bdi>{}</bdi>", esc(s))
}

