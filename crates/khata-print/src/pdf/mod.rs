/// The language the PDF's labels are in.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum PdfLabels {
    #[default]
    English,
    /// English with Arabic, left to right (KSA and UAE invoices).
    Bilingual,
    /// Arabic, on a right-to-left page: the layout mirrored, every column
    /// right-aligned, Arabic month names. Amounts, quantities, dates and
    /// page numbers print in Arabic-Indic digits (٠١٢…) when
    /// `arabic_indic_digits` is set; identifiers (tax numbers, invoice
    /// numbers, bank accounts) keep their digits as typed.
    Arabic { arabic_indic_digits: bool },
}

/// One document of a PDF: the invoice and how it looks.
pub struct PdfDoc<'a> {
    pub doc: &'a InvoiceDoc,
    pub look: Look<'a>,
    pub labels: PdfLabels,
}

/// A PDF with each document starting on a new page.
pub fn invoices_pdf(h: &Header, docs: &[PdfDoc]) -> Vec<u8> {
    writer::write(&layout::layout(h, docs).display)
}

/// Every text run the PDF of [`invoices_pdf`] draws, in logical order
/// (before shaping and reordering), page by page.
pub fn invoices_pdf_text(h: &Header, docs: &[PdfDoc]) -> Vec<String> {
    layout::layout(h, docs).texts
}

/// How many QR codes the PDF of [`invoices_pdf`] draws (tests: the ZATCA,
/// IRN and CFDI codes are on the page).
pub fn invoices_pdf_qr_codes(h: &Header, docs: &[PdfDoc]) -> usize {
    layout::layout(h, docs).qr_codes
}

