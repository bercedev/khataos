}

val tauriProperties = Properties().apply {
    val propFile = file("tauri.properties")
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}

// Release signing with the Play upload key. Nothing secret lives in this file
// or in the repository: the keystore path and passwords come from environment
// variables (docs/mobile.md, "Android: Google Play"). Without
// KHATAOS_ANDROID_KEYSTORE a release build is left unsigned, as before.
fun env(name: String): String? = System.getenv(name)?.takeIf { it.isNotBlank() }
val releaseKeystore = env("KHATAOS_ANDROID_KEYSTORE")

android {
    compileSdk = 37
    namespace = "org.khataos.mobile"
    defaultConfig {
        manifestPlaceholders["usesCleartextTraffic"] = "false"
        applicationId = "org.khataos.mobile"
        minSdk = 24
        targetSdk = 37
        versionCode = tauriProperties.getProperty("tauri.android.versionCode", "1").toInt()
        versionName = tauriProperties.getProperty("tauri.android.versionName", "1.0")
    }
    signingConfigs {
        if (releaseKeystore != null) {
            create("release") {
                storeFile = file(releaseKeystore)
                storePassword = env("KHATAOS_ANDROID_KEYSTORE_PASSWORD")
                    ?: error("KHATAOS_ANDROID_KEYSTORE is set but KHATAOS_ANDROID_KEYSTORE_PASSWORD is not")
                keyAlias = env("KHATAOS_ANDROID_KEY_ALIAS") ?: "upload"
                keyPassword = env("KHATAOS_ANDROID_KEY_PASSWORD") ?: storePassword
            }
        }
    }
    buildTypes {
        getByName("debug") {
            manifestPlaceholders["usesCleartextTraffic"] = "true"
            isDebuggable = true
            isJniDebuggable = true
            isMinifyEnabled = false
            packaging {
                jniLibs.keepDebugSymbols.add("*/arm64-v8a/*.so")
                jniLibs.keepDebugSymbols.add("*/armeabi-v7a/*.so")
                jniLibs.keepDebugSymbols.add("*/x86/*.so")
                jniLibs.keepDebugSymbols.add("*/x86_64/*.so")
            }
        }
        getByName("release") {
            if (releaseKeystore != null) {
                signingConfig = signingConfigs.getByName("release")
            }
            optimization {
               enable = true
            }
            proguardFiles(
                *fileTree(".") {
                  include("**/*.pro")
                  exclude("build/**")
                }.files.toTypedArray()
            )
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_1_8
        targetCompatibility = JavaVersion.VERSION_1_8
    }
    buildFeatures {
        buildConfig = true
    }
}

kotlin {
    compilerOptions {
        jvmTarget = JvmTarget.JVM_1_8
    }
}

