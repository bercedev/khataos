/// Print-ready HTML for one cheque, positioned for `layout`.
pub fn cheque_html(cheque: &ChequeDoc, layout: &ChequeLayout, grouping: Grouping) -> String {
    let at = |x: f32, y: f32| format!("left:{x}mm;top:{y}mm");
    let digits = cheque.date.format("%d%m%Y").to_string();
    let date: String = digits
        .chars()
        .enumerate()
        .map(|(i, c)| {
            format!(
                "<span class=\"f\" style=\"{};width:{}mm;text-align:center\">{c}</span>",
                at(layout.date_x + i as f32 * layout.date_box, layout.date_y),
                layout.date_box
            )
        })
        .collect();
    let crossing = if cheque.account_payee {
        "<div class=\"cross\"><span>A/c Payee</span></div>"
    } else {
        ""
    };
    format!(
        "<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\"><title>Cheque — {payee}</title><style>\
@page {{ size: {w}mm {h}mm; margin: 0; }} body {{ margin: 0; font: 11pt system-ui, sans-serif; color: #000; }} \
.cheque {{ position: relative; width: {w}mm; height: {h}mm; overflow: hidden; }} .f {{ position: absolute; white-space: nowrap; }} \
.words {{ white-space: normal; line-height: 7.5mm; text-indent: 0; }} \
.cross {{ position: absolute; left: 4mm; top: 4mm; width: 34mm; height: 10mm; border-top: 0.4mm solid #000; border-bottom: 0.4mm solid #000; transform: rotate(-20deg); text-align: center; font-size: 9pt; line-height: 10mm; }} \
@media screen {{ body {{ background: #eee; padding: 10mm; }} .cheque {{ background: #fff; outline: 0.3mm dashed #999; }} }}\
</style></head><body><div class=\"cheque\">{crossing}{date}\
<span class=\"f\" style=\"{payee_at}\">{payee}</span>\
<span class=\"f words\" style=\"{words_at};width:{words_w}mm\">{words}</span>\
<span class=\"f\" style=\"{fig_at}\">{figures}/-</span></div></body></html>",
        payee = esc(&cheque.payee),
        w = layout.width,
        h = layout.height,
        payee_at = at(layout.payee_x, layout.payee_y),
        words_at = at(layout.words_x, layout.words_y),
        words_w = layout.words_width,
        words = esc(&cheque.amount_in_words),
        fig_at = at(layout.figures_x, layout.figures_y),
        figures = format_amount(cheque.amount, grouping, 2),
    )
}

/// CSV (RFC 4180) with plain decimal amounts, for Excel and CA tools.
pub fn trial_balance_csv(rows: &[TrialBalanceRow], opening_stock: Amount) -> String {
    let field = |s: &str| {
        if s.contains([',', '"', '\n', '\r']) { format!("\"{}\"", s.replace('"', "\"\"")) } else { s.to_owned() }
    };
    let mut out = String::from("Particulars,Debit,Credit\r\n");
    for r in rows {
        out.push_str(&format!("{},{},{}\r\n", field(&r.name), r.debit, r.credit));
    }
    if !opening_stock.is_zero() {
        out.push_str(&format!("Opening Stock,{opening_stock},0\r\n"));
    }
    out
}

