//! Prints the key reference table in `docs/guide/keyboard.md` from the
//! default key map, so the guide never drifts from `src/tally.rs`.
//!
//! ```sh
//! cargo run -p khata-keymap --example keymap-doc            # print the table
//! cargo run -p khata-keymap --example keymap-doc -- --write # update the guide
//! ```
//!
//! `scripts/keymap-doc` runs the second command. The test in
//! `tests/keyboard_doc.rs` fails when the guide is out of date.
//!
//! Every action needs a plain-English line and a status here; the `match` is
//! exhaustive, so a new action does not compile until it is described. The
//! status says whether the desktop app handles the key today. Keep it honest:
//! a key that is bound but not built is "Not yet" (the test checks this
//! against `NOT_BUILT` in `apps/desktop/src/shell.ts`).

use khata_keymap::{Action, Context, GatewayItem, Keymap, VoucherKey};

/// Markers around the generated block in the guide page.
pub const START: &str =
    "<!-- keymap-doc:start (generated by scripts/keymap-doc; do not edit by hand) -->";
pub const END: &str = "<!-- keymap-doc:end -->";

/// The guide page, relative to this crate.
pub const GUIDE: &str = "../../docs/guide/keyboard.md";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Status {
    /// Works wherever it makes sense.
    Yes,
    /// Works on some screens only; the note says where.
    Partly(&'static str),
    /// Bound for muscle memory, but nothing is built behind it yet.
    NotYet,
}

impl Status {
    fn cell(self) -> String {
        match self {
            Status::Yes => "Yes".to_owned(),
            Status::Partly(note) => format!("Partly: {note}"),
            Status::NotYet => "Not yet".to_owned(),
        }
    }
}

