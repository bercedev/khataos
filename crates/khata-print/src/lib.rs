/// An Arabic document: the same header and tables as [`Doc`], right to left.
struct ArDoc<'a> {
    h: &'a Header<'a>,
    body: String,
}

impl<'a> ArDoc<'a> {
    /// `title` and `period` are Arabic text with any user data already escaped.
    fn new(h: &'a Header<'a>, title: &str, period: &str) -> Self {
        let body = format!(
            "<header><h1><bdi>{}</bdi></h1><div class=\"addr\" dir=\"auto\">{}</div><h2>{title}</h2><div class=\"period\">{period}</div></header>",
            esc(h.company),
            esc(h.address),
        );
        Self { h, body }
    }

    fn amt(&self, a: Amount) -> String {
        if a.is_zero() { String::new() } else { format_amount(a, self.h.grouping, 2) }
    }

    fn fig(&self, a: Amount) -> String {
        format_amount(a, self.h.grouping, 2)
    }

    /// A balance with مدين / دائن, as on screen.
    fn bal(&self, a: Amount) -> String {
        if a.is_zero() {
            "صفر".into()
        } else {
            format!("{} {}", format_amount(a.abs(), self.h.grouping, 2), if a.is_sign_positive() { "مدين" } else { "دائن" })
        }
    }

    /// Cells are HTML (escape user data with `esc` or `bdi`); amounts are plain text.
    fn table(&mut self, heads: &[(&str, bool)], rows: &[Vec<String>], total: Option<Vec<String>>) {
        let numeric: Vec<bool> = heads.iter().map(|(_, n)| *n).collect();
        self.body.push_str("<table><thead><tr>");
        for (h, n) in heads {
            self.body.push_str(&format!("<th{}>{h}</th>", if *n { " class=\"num\"" } else { "" }));
        }
        self.body.push_str("</tr></thead><tbody>");
        let mut row = |cells: &[String], cls: &str| {
            self.body.push_str(&format!("<tr{cls}>"));
            for (i, c) in cells.iter().enumerate() {
                let num = numeric.get(i).copied().unwrap_or(false);
                self.body.push_str(&format!("<td{}>{c}</td>", if num { " class=\"num\"" } else { "" }));
            }
            self.body.push_str("</tr>");
        };
        for r in rows {
            row(r, "");
        }
        if let Some(t) = total {
            row(&t, " class=\"total\"");
        }
        self.body.push_str("</tbody></table>");
    }

    fn finish(self, title: &str, extra_css: &str) -> String {
        format!(
            "<!doctype html><html lang=\"ar\" dir=\"rtl\"><head><meta charset=\"utf-8\"><title>{title} — {}</title><style>{CSS}{extra_css}{AR_CSS}</style></head>\
             <body dir=\"rtl\" lang=\"ar\"><main class=\"ar\" dir=\"rtl\" lang=\"ar\">{}<footer>أُعدّ بواسطة <bdi>KhataOS</bdi></footer></main></body></html>",
            esc(self.h.company),
            self.body
        )
    }
}

/// ميزان المراجعة: [`trial_balance_html`] in Arabic.
pub fn trial_balance_html_ar(h: &Header, as_at: NaiveDate, rows: &[TrialBalanceRow], opening_stock: Amount) -> String {
    let mut d = ArDoc::new(h, "ميزان المراجعة", &format!("كما في {}", date_ar(as_at)));
    let mut body: Vec<Vec<String>> = rows.iter().map(|r| vec![bdi(&r.name), d.amt(r.debit), d.amt(r.credit)]).collect();
    if !opening_stock.is_zero() {
        body.push(vec!["مخزون أول المدة".into(), d.amt(opening_stock), String::new()]);
    }
    let dr: Amount = rows.iter().map(|r| r.debit).sum::<Amount>() + opening_stock;
    let cr: Amount = rows.iter().map(|r| r.credit).sum();
    let total = vec!["الإجمالي العام".into(), d.amt(dr), d.amt(cr)];
    d.table(&[("اسم الحساب", false), ("مدين", true), ("دائن", true)], &body, Some(total));
    d.finish("ميزان المراجعة", "")
}

/// دفتر اليومية: [`day_book_html`] in Arabic.
