    /// The objects of a PDF from this writer: number → (dictionary, inflated stream).
    fn objects(pdf: &[u8]) -> std::collections::HashMap<usize, (String, Vec<u8>)> {
        let mut out = std::collections::HashMap::new();
        let mut at = 0;
        while let Some(i) = find(&pdf[at..], b" 0 obj\n") {
            let head = &pdf[..at + i];
            let num_start = head.iter().rposition(|&b| b == b'\n').map_or(0, |p| p + 1);
            let id: usize = std::str::from_utf8(&head[num_start..]).unwrap().parse().unwrap();
            let body = at + i + 7;
            let end = body + find(&pdf[body..], b"\nendobj\n").unwrap();
            let obj = &pdf[body..end];
            let (dict, data) = match find(obj, b"stream\n") {
                Some(s) => {
                    let raw = &obj[s + 7..obj.len() - 10];
                    let mut z = ZlibDecoder::new(raw);
                    let mut buf = Vec::new();
                    if z.read_to_end(&mut buf).is_err() {
                        buf = raw.to_vec();
                    }
                    (String::from_utf8_lossy(&obj[..s]).into_owned(), buf)
                }
                None => (String::from_utf8_lossy(obj).into_owned(), Vec::new()),
            };
            out.insert(id, (dict, data));
            at = end + 8;
        }
        out
    }

    /// The object number after `key` in a dictionary ("/ToUnicode 9 0 R").
    fn reference(dict: &str, key: &str) -> Option<usize> {
        dict.split(key).nth(1)?.split_whitespace().next()?.parse().ok()
    }

    /// A ToUnicode map: code → text.
    fn bfchars(cmap: &[u8]) -> std::collections::HashMap<u16, String> {
        let s = String::from_utf8_lossy(cmap);
        let mut out = std::collections::HashMap::new();
        for line in s.lines().filter(|l| l.starts_with('<') && l.contains("> <")) {
            let (code, text) = line.split_once("> <").unwrap();
            let code = u16::from_str_radix(&code[1..], 16).unwrap();
            let units: Vec<u16> = text.trim_end_matches('>').as_bytes().chunks(4).map(|h| u16::from_str_radix(std::str::from_utf8(h).unwrap(), 16).unwrap()).collect();
            out.insert(code, String::from_utf16(&units).unwrap());
        }
        out
    }

    /// The text of every text object, as a PDF reader gets it: the codes'
    /// ToUnicode text in drawing (visual) order, one string per text object.
    fn extract(pdf: &[u8]) -> Vec<String> {
        let objs = objects(pdf);
        let mut ids: Vec<&usize> = objs.keys().collect();
        ids.sort();
        let mut runs = Vec::new();
        for id in ids {
            let (dict, _) = &objs[id];
            if !dict.contains("/Type /Page ") {
                continue;
            }
            // /F1 12 0 R … → ToUnicode maps.
            let fonts_part = dict.split("/Font << ").nth(1).unwrap().split(" >>").next().unwrap();
            let mut maps = std::collections::HashMap::new();
            let toks: Vec<&str> = fonts_part.split_whitespace().collect();
            for t in toks.chunks(4) {
                let font: usize = t[1].parse().unwrap();
                let tu = reference(&objs[&font].0, "/ToUnicode ").unwrap();
                maps.insert(t[0].to_owned(), bfchars(&objs[&tu].1));
            }
            let content = String::from_utf8_lossy(&objs[&reference(dict, "/Contents ").unwrap()].1).into_owned();
            let mut cur = String::new();
            let mut font = String::new();
            let mut text = String::new();
            for tok in content.split(|c: char| c.is_whitespace() || c == '[' || c == ']') {
                if tok.starts_with("/F") {
                    font = tok.to_owned();
                } else if tok == "ET" {
                    runs.push(std::mem::take(&mut text));
                } else {
                    // Hex strings, possibly several with adjustments between: <0001><0002>-12<0003>
                    cur.clear();
                    for part in tok.split('<').skip(1) {
                        let hex = part.split('>').next().unwrap();
                        for code in hex.as_bytes().chunks(4) {
                            let code = u16::from_str_radix(std::str::from_utf8(code).unwrap(), 16).unwrap();
                            text.push_str(maps[&font].get(&code).map_or("", String::as_str));
                        }
                    }
                }
            }
        }
        runs
    }

    /// Visual-order Arabic back in reading order (each glyph's text kept whole).
    fn logical(visual: &str) -> String {
        // Clusters are one code each here: reverse the characters, then put
        // each letter's marks back after it.
        let mut out: Vec<char> = visual.chars().rev().collect();
        let is_mark = |c: char| ('\u{064B}'..='\u{065F}').contains(&c) || c == '\u{0670}';
        let mut i = 0;
        while i + 1 < out.len() {
            if is_mark(out[i]) && !is_mark(out[i + 1]) {
                out.swap(i, i + 1);
                i += 1;
            }
            i += 1;
        }
        out.into_iter().collect()
    }

